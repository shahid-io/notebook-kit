#!/usr/bin/env bash
# Package this pipeline as a standalone repo somebody else can clone and use.
#
#   bash share.sh ~/Desktop/notebook-kit
#
# Copies the engine, the build script, the docs and the template book. Leaves
# behind the written books, the lecture transcripts and every generated PDF,
# because those are yours and they are what makes the directory large.
#
# The result is a git repository with one commit. Push it anywhere, or zip it.
set -e
cd "$(dirname "$0")"

DEST="${1:-}"
[ -z "$DEST" ] && { echo "usage: bash share.sh <destination-directory>"; exit 1; }
[ -e "$DEST" ] && { echo "share.sh: $DEST already exists. Pick a new path."; exit 1; }

mkdir -p "$DEST/engine" "$DEST/books/figures" "$DEST/sources"

cp engine/build.py engine/pdf.py engine/lint.py engine/questions.py \
   engine/sketch.py engine/transcript.py engine/theme.css "$DEST/engine/"
cp -R engine/fonts "$DEST/engine/fonts"
cp books/example.md "$DEST/books/"
cp books/figures/example.py "$DEST/books/figures/"
cp README.md GETTING-STARTED.md AUTHORING.md share.sh "$DEST/"

# The registry with the personal books removed, and the README's table of
# those books replaced by what the packaged copy actually contains.
# Shipping a contents page for files that are not there is worse than
# shipping no table at all.
python3 - "$DEST" <<'PY'
import re, sys, pathlib
dest = pathlib.Path(sys.argv[1])
s = pathlib.Path("build.sh").read_text()
s = re.sub(r"BOOKS=\(\n(?:.*\n)*?\)",
           'BOOKS=(\n'
           '  # add one line per book. nothing else needs to know about it.\n'
           ')', s, count=1)
(dest / "build.sh").write_text(s)

r = pathlib.Path("README.md").read_text()
r = re.sub(r"\| # \| Book \| Source \| Built from \|\n(?:\|.*\|\n)+",
           "| # | Book | Source | What it is |\n"
           "|---|---|---|---|\n"
           "| XX | Example Book | `books/example.md` | The template. "
           "Every directive and mark, rendered |\n"
           "| 00 | Question Bank | `books/question-bank.md` | Generated "
           "once you have books to collect from |\n", r, count=1)
r = r.replace("bash build.sh object-storage         # one book, Reading edition\n"
              "bash build.sh object-storage tablet  # one book, one named edition",
              "bash build.sh example                # one book, Reading edition\n"
              "bash build.sh example tablet         # one book, one named edition")
r = r.replace(":::figure authz-layers", ":::figure request-path")
(dest / "README.md").write_text(r)
PY

# Keep this verbatim MIT. GitHub's licence detection is exact-match, and an
# appended note about the fonts makes the repo show as "Other". The font
# caveat lives in the README and in engine/fonts/NOTICE.md instead.
