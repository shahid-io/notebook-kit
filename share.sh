cat > "$DEST/.gitignore" <<'GI'
__pycache__/
.DS_Store
html/
pdf/
GI

cat > "$DEST/books/README.md" <<'BR'
# books/

One markdown file per book, plus `figures/<book>.py` for any hand-drawn
figures. `example.md` is the template: copy it, then add a line to the `BOOKS`
array in `../build.sh`.

`question-bank.md` is generated by `engine/questions.py` on every build once you
have books to collect from. Never edit it; edit the book the prompt came from.
BR

cat > "$DEST/sources/README.md" <<'SR'
# sources/

Lecture transcripts, if you build books from video. Pull them with:

    python3 engine/transcript.py "<playlist or video url>" sources

One file per video, front matter plus timestamped paragraphs. These are raw
material, not notes, and are not meant to be read straight through.
SR

cd "$DEST"
git init -q
git add -A
# Use whatever git identity is configured here; fall back only if there is none,
# so the first commit is not authored by a placeholder.
if git config user.email >/dev/null 2>&1 || git config --global user.email >/dev/null 2>&1; then
  git commit -qm "Study notebook pipeline: markdown to annotatable PDF"
else
  git -c user.name="notebook-kit" -c user.email="noreply@localhost" \
      commit -qm "Study notebook pipeline: markdown to annotatable PDF"
fi

echo "Packaged into $DEST"
echo
echo "  cd $DEST && bash build.sh example"
echo
echo "Then push it wherever you like:"
echo "  gh repo create <name> --private --source=$DEST --push"
